// The agent's script never becomes module source: it reaches the guest as data and compiles as an async function's body.
// Nothing in the guest is a boundary: the host parses every line with `guestMessage` and checks every call.
import { stripTypeScriptTypes } from "node:module";
import type { HostReply, RunError } from "@oriel/core";
import { type Fn, globalsOf, parameters, pathOf } from "./describe.ts";

// Reply 0 carries the script; the guest's own reads count from 1.
// Console output becomes log messages, so nothing else reaches stdout.
const runtime = String.raw`// Generated by @oriel/bindings.
const __oriel = (() => {
  const deno = globalThis.Deno;
  const encoder = new TextEncoder();
  const AsyncFunction = (async () => {}).constructor;
  const send = (message) => {
    const line = JSON.stringify(message) + "\n";
    if (!deno) {
      process.stdout.write(line);
      return;
    }
    const bytes = encoder.encode(line);
    for (let at = 0; at < bytes.length; ) at += deno.stdout.writeSync(bytes.subarray(at));
  };
  const freeze = (value) => {
    if (value === null || typeof value !== "object") return value;
    for (const inner of Object.values(value)) freeze(inner);
    return Object.freeze(value);
  };
  const pending = new Map();
  let reads = 0;
  let refs = 0;
  let stop = null;
  const settle = (line) => {
    if (!line.trim()) return;
    const reply = JSON.parse(line);
    const waiter = pending.get(reply.id);
    if (!waiter) return;
    pending.delete(reply.id);
    if (reply.ok) waiter.resolve(freeze(reply.value));
    else waiter.reject(new Error(String(reply.error)));
  };
  const listen = () => {
    let buffer = "";
    const take = (text) => {
      buffer += text;
      for (let end = buffer.indexOf("\n"); end >= 0; end = buffer.indexOf("\n")) {
        const line = buffer.slice(0, end);
        buffer = buffer.slice(end + 1);
        settle(line);
      }
    };
    if (!deno) {
      process.stdin.setEncoding("utf8");
      process.stdin.on("data", take);
      stop = () => process.stdin.destroy();
      return;
    }
    const reader = deno.stdin.readable.pipeThrough(new TextDecoderStream()).getReader();
    stop = () => reader.cancel();
    (async () => {
      for (let chunk = await reader.read(); !chunk.done; chunk = await reader.read()) take(chunk.value);
    })();
  };
  const trim = (args) => {
    const kept = [...args];
    while (kept.length && kept[kept.length - 1] === undefined) kept.pop();
    return kept;
  };
  const read = (fn, args) => {
    const id = ++reads;
    send({ kind: "read", id, fn, args: trim(args) });
    return new Promise((resolve, reject) => pending.set(id, { resolve, reject }));
  };
  const write = (fn, args, creates) => {
    const ref = creates ? "new:" + (refs + 1) : null;
    send({ kind: "write", fn, args: trim(args), ref });
    if (creates) refs += 1;
    return ref ?? undefined;
  };
  const intend = (fn, args) => {
    send({ kind: "intent", fn, args: trim(args) });
  };
  const draft = (fn, args) => {
    send({ kind: "draft", fn, args: trim(args) });
  };
  // An error shows its name and message, a Map or Set its entries; at most 50
  // entries each and 4000 characters a value.
  const plain = (key, value) => {
    if (value instanceof Error) return value.name + ": " + value.message;
    if (value instanceof Map) return { ["Map(" + value.size + ")"]: [...value].slice(0, 50) };
    if (value instanceof Set) return { ["Set(" + value.size + ")"]: [...value].slice(0, 50) };
    if (typeof value === "bigint") return value + "n";
    return value;
  };
  const text = (value) => {
    if (typeof value === "string") return value;
    if (value instanceof Error) return plain("", value);
    try {
      return JSON.stringify(value, plain) ?? String(value);
    } catch {
      return String(value);
    }
  };
  const show = (value) => {
    const shown = text(value);
    return shown.length > 4000 ? shown.slice(0, 4000) + "…" : shown;
  };
  const log = (...values) => send({ kind: "log", text: values.map(show).join(" ") });
  // These five methods become log messages and can't be replaced or removed.
  // The object stays extensible: Deno's node: modules add to it as they load.
  const logger = {};
  for (const name of ["log", "info", "warn", "error", "debug"])
    Object.defineProperty(logger, name, { value: log, enumerable: true, writable: false, configurable: false });
  globalThis.console = logger;
  const run = async (bindings, body) => {
    try {
      const parameters = ${JSON.stringify(parameters)};
      for (const name of Object.keys(bindings))
        if (!parameters.includes(name))
          Object.defineProperty(globalThis, name, { value: bindings[name], writable: false, configurable: false });
      const script = new AsyncFunction(...parameters, body);
      const value = await script(...parameters.map((name) => bindings[name]));
      send({ kind: "done", value: value === undefined ? null : value });
    } catch (error) {
      send({ kind: "threw", message: error instanceof Error ? String(error.stack ?? error) : String(error) });
    }
    stop?.();
  };
  const start = (bindings) => {
    pending.set(0, {
      resolve: (body) => run(bindings, String(body)),
      reject: (error) => {
        send({ kind: "threw", message: error.message });
        stop?.();
      },
    });
    listen();
  };
  return { read, write, intend, draft, start };
})();
`;

// Each forwards its arguments untouched; the host validates them.
export function stubs(fns: readonly Fn[], spaces: readonly string[]): string {
  const call = (fn: Fn) => {
    const path = JSON.stringify(pathOf(fn));
    if (fn.kind === "read") return `(...args: unknown[]) => __oriel.read(${path}, args)`;
    if (fn.kind === "intent") return `(...args: unknown[]): void => __oriel.intend(${path}, args)`;
    if (fn.kind === "draft") return `(...args: unknown[]): void => __oriel.draft(${path}, args)`;
    return `(...args: unknown[]) => __oriel.write(${path}, args, ${fn.creates})`;
  };
  // Every namespace, even an empty one, so each name the guest passes the script exists.
  return [
    ...spaces.flatMap((space) => [
      `const ${space} = Object.freeze({`,
      ...fns.filter((fn) => fn.space === space).map((fn) => `  ${fn.name}: ${call(fn)},`),
      "});",
    ]),
    ...fns.filter((fn) => fn.space === null).map((fn) => `const ${fn.name} = ${call(fn)};`),
    // A parameter this module doesn't declare is still handed to the script, as nothing.
    ...parameters
      .filter((name) => !fns.some((fn) => fn.space === null && fn.name === name))
      .map((name) => `const ${name} = undefined;`),
    "",
  ].join("\n");
}

export const shimFor = (fns: readonly Fn[], spaces: readonly string[]): string =>
  `${runtime}${stubs(fns, spaces)}__oriel.start({ ${globalsOf(spaces).join(", ")} });\n`;

// The opening line is its own, so script line N is line N + 1.
const opening = "async function __script() {\n";
const closing = "\n}\n";
export const wrap = (script: string): string => opening + script + closing;

// The compiled body opens with a "use strict" line, after the two lines the
// AsyncFunction constructor puts before every body (ECMA-262,
// CreateDynamicFunction). So a runtime error at line L of the compiled
// function is at line L - 3 of the script, same column.
export const scriptLineOffset = 3;

type Compile = new (...paramsThenBody: string[]) => unknown;
const AsyncFunction = (async () => {}).constructor as Compile;

const refuse = (detail: string): { ok: false; error: RunError } => ({
  ok: false,
  error: {
    phase: "typecheck",
    message: `The script doesn't compile as the body of an async function: ${detail}`,
    hint: "Write statements only: no import or export declarations, nothing that closes the body early, and only types that erase (no enum, namespace or parameter properties).",
    logs: [],
  },
});

const firstLine = (error: unknown) =>
  (error instanceof Error ? `${error.name}: ${error.message}` : String(error)).split("\n")[0] ?? "";

// Node's stripper (SWC in WebAssembly) runs out of stack near 1,000 nested brackets,
// and then fails for the rest of its thread.
export const maxScriptBytes = 64 * 1024;
export const maxNesting = 256;

// Rough on purpose: a bracket inside a string counts too, so it can over-refuse, rarely.
export function nesting(script: string): number {
  let depth = 0;
  let deepest = 0;
  for (const char of script) {
    if (char === "(" || char === "[" || char === "{") deepest = Math.max(deepest, ++depth);
    else if (char === ")" || char === "]" || char === "}") depth -= 1;
  }
  return deepest;
}

// A function body can't hold an import or export, and parses on its own, so the script can't close it early.
// Run it off the main thread, in a worker replaced after any failure: deep expressions can still break the stripper for good.
export function guestStart(
  script: string,
): { ok: true; reply: HostReply } | { ok: false; error: RunError } {
  const bytes = Buffer.byteLength(script, "utf8");
  if (bytes > maxScriptBytes)
    return {
      ok: false,
      error: {
        phase: "limit",
        message: `The script is ${bytes} bytes; the most is ${maxScriptBytes}.`,
        logs: [],
      },
    };
  if (nesting(script) > maxNesting)
    return {
      ok: false,
      error: {
        phase: "typecheck",
        message: `The script nests brackets more than ${maxNesting} deep.`,
        hint: "Flatten it: name intermediate values instead of nesting expressions.",
        logs: [],
      },
    };
  const wrapped = wrap(script);
  let stripped: string;
  try {
    stripped = stripTypeScriptTypes(wrapped, { mode: "strip" });
  } catch (error) {
    return refuse(firstLine(error));
  }
  const intact =
    stripped.length === wrapped.length &&
    stripped.startsWith(opening) &&
    stripped.endsWith(closing);
  if (!intact) return refuse("stripping its types moved it");
  const body = `"use strict";\n${stripped.slice(opening.length, stripped.length - closing.length)}`;
  try {
    new AsyncFunction(...parameters, body);
  } catch (error) {
    return refuse(firstLine(error));
  }
  return { ok: true, reply: { id: 0, ok: true, value: body } };
}
