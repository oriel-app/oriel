// The guest side: a fixed runtime that speaks core's guest protocol, then
// stubs generated from the description. Deno runs it as TypeScript, joined
// with the agent's script by `guestEntry`. Nothing in the guest is a boundary:
// the host parses every line with `guestMessage` and checks every call.
import { type Fn, pathOf } from "./describe.ts";

// JSON lines: calls go out on stdout, read replies come back on stdin. Reads
// await their reply; writes are sent in call order and never awaited. A create
// names its item `new:N`, counting from 1 within the run. Console output
// becomes log messages, so nothing else reaches stdout. Under Node (tests
// only) stdio is `process`'s.
const runtime = String.raw`// Generated by @oriel/bindings.
const __oriel = (() => {
  const deno = globalThis.Deno;
  const encoder = new TextEncoder();
  const send = (message) => {
    const line = JSON.stringify(message) + "\n";
    if (!deno) {
      process.stdout.write(line);
      return;
    }
    const bytes = encoder.encode(line);
    for (let at = 0; at < bytes.length; ) at += deno.stdout.writeSync(bytes.subarray(at));
  };
  const freeze = (value) => {
    if (value === null || typeof value !== "object") return value;
    for (const inner of Object.values(value)) freeze(inner);
    return Object.freeze(value);
  };
  const pending = new Map();
  let reads = 0;
  let refs = 0;
  let stop = null;
  const settle = (line) => {
    if (!line.trim()) return;
    const reply = JSON.parse(line);
    const waiter = pending.get(reply.id);
    if (!waiter) return;
    pending.delete(reply.id);
    if (reply.ok) waiter.resolve(freeze(reply.value));
    else waiter.reject(new Error(String(reply.error)));
  };
  const listen = () => {
    if (stop) return;
    let buffer = "";
    const take = (text) => {
      buffer += text;
      for (let end = buffer.indexOf("\n"); end >= 0; end = buffer.indexOf("\n")) {
        const line = buffer.slice(0, end);
        buffer = buffer.slice(end + 1);
        settle(line);
      }
    };
    if (!deno) {
      process.stdin.setEncoding("utf8");
      process.stdin.on("data", take);
      stop = () => process.stdin.destroy();
      return;
    }
    const reader = deno.stdin.readable.pipeThrough(new TextDecoderStream()).getReader();
    stop = () => reader.cancel();
    (async () => {
      for (let chunk = await reader.read(); !chunk.done; chunk = await reader.read()) take(chunk.value);
    })();
  };
  const trim = (args) => {
    const kept = [...args];
    while (kept.length && kept[kept.length - 1] === undefined) kept.pop();
    return kept;
  };
  const read = (fn, args) => {
    listen();
    const id = ++reads;
    send({ kind: "read", id, fn, args: trim(args) });
    return new Promise((resolve, reject) => pending.set(id, { resolve, reject }));
  };
  const write = (fn, args, creates) => {
    const ref = creates ? "new:" + (refs + 1) : null;
    send({ kind: "write", fn, args: trim(args), ref });
    if (creates) refs += 1;
    return ref ?? undefined;
  };
  const show = (value) => {
    if (typeof value === "string") return value;
    try {
      return JSON.stringify(value) ?? String(value);
    } catch {
      return String(value);
    }
  };
  const log = (...values) => send({ kind: "log", text: values.map(show).join(" ") });
  globalThis.console = Object.freeze({ log, info: log, warn: log, error: log, debug: log });
  const run = async (body) => {
    try {
      const value = await body();
      send({ kind: "done", value: value === undefined ? null : value });
    } catch (error) {
      send({ kind: "threw", message: error instanceof Error ? String(error.stack ?? error) : String(error) });
    }
    stop?.();
  };
  return { read, write, run };
})();
`;

// One stub per function. Each forwards its arguments untouched; the host
// validates them. Typed, so a test can check the stubs against the
// declarations.
export function stubs(fns: readonly Fn[]): string {
  const call = (fn: Fn) => {
    const path = JSON.stringify(pathOf(fn));
    if (fn.kind === "read") return `(...args: unknown[]) => __oriel.read(${path}, args)`;
    return `(...args: unknown[]) => __oriel.write(${path}, args, ${fn.creates})`;
  };
  return [
    "const jira = Object.freeze({",
    ...fns.filter((fn) => fn.space === "jira").map((fn) => `  ${fn.name}: ${call(fn)},`),
    "});",
    ...fns.filter((fn) => fn.space === null).map((fn) => `const ${fn.name} = ${call(fn)};`),
    "",
  ].join("\n");
}

export const shimFor = (fns: readonly Fn[]): string => runtime + stubs(fns);

// The agent's script is the body of an async function. The opening line is
// its own, so script line N is line N + 1 here. The typecheck wraps it the
// same way, so the two agree on what the script means.
export const wrap = (script: string): string => `__oriel.run(async () => {\n${script}\n});\n`;

// The one file the sandbox runs: the shim, then the wrapped script.
// `firstLine` is the entry line holding the script's first line, for mapping
// runtime errors back to the script.
export function guestEntry(shim: string, script: string): { source: string; firstLine: number } {
  const body = shim.endsWith("\n") ? shim : `${shim}\n`;
  return { source: body + wrap(script), firstLine: body.split("\n").length + 1 };
}
